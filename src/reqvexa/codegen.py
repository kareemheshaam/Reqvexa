from reqvexa.models import HttpRequest, ValueObservation
from reqvexa.provenance import Analysis

_REGENERATED_HEADERS = frozenset({
    "content-length",
    "host",
    "transfer-encoding",
})

_DYNAMIC_MARKER_PREFIX = "__REQVEXA_DYNAMIC_"


@dataclass(frozen=True)
class _DynamicBinding:
    marker: str
    producer_index: int | None
    header_name: str | None
    operations: tuple[str, ...]
    variable_name: str | None = None
    note: str = ""


def generate_python(
    requests: Iterable[HttpRequest],
    *,
    analysis: Analysis | None = None,
    asynchronous: bool = False,
    single_request: bool = False,
) -> str:
    """Generate a tls_client replay from captured requests.

    Flow mode preserves request ordering and analyzed response dependencies.
    Single-request mode emits one independent, direct-method request and
    keeps its captured values literal. Async mode uses AsyncSession in either
    generation mode.
    """
    request_list = sorted(requests, key=lambda item: (item.sequence, item.id))
    if not request_list:
        raise ValueError("Select at least one request to generate code.")
    if single_request and len(request_list) != 1:
        raise ValueError("Select exactly one request for single-request code.")
    if single_request:
        return _generate_single_request_python(
            request_list[0], asynchronous=asynchronous,
        )

    configs = [_request_config(request) for request in request_list]
    bindings = (
        _dependency_bindings(request_list, configs, analysis)
        if analysis is not None else []
    )
    rendered_configs = pformat(
        configs,
        width=88,
        sort_dicts=False,
        compact=False,
    )
    manual_bindings = [item for item in bindings if item.variable_name is not None]
    header_bindings = [item for item in bindings if item.header_name is not None]
    manual_values = _render_manual_bindings(manual_bindings)
    rendered_header_bindings = _render_header_bindings(header_bindings)
    mode_import = "import asyncio\n" if asynchronous else ""
    flow = _async_flow() if asynchronous else _sync_flow()
    return (
        "# Generated by Reqvexa. Install the runtime with: pip install tls-client\n"
        "# Review captured credentials before sharing.\n"
        f"{mode_import}import base64\n"
        "from urllib.parse import quote, quote_plus, unquote\n"
        "import tls_client\n\n"
        f"REQUESTS = {rendered_configs}\n\n"
        f"{manual_values}"
        f"HEADER_BINDINGS = {rendered_header_bindings}\n\n"
        f"{_runtime_helpers()}"
        f"{flow}"
    )


def _request_config(request: HttpRequest) -> dict[str, Any]:
    pseudo_headers: dict[str, str] = {}
    request_headers: dict[str, str] = {}
    header_names: dict[str, str] = {}
    header_order: list[str] = []
    cookie_values: dict[str, str] = {}
    host_header = ""
    cookie_header_seen = False

    for header in request.headers:
        name = header.name.strip()
        folded = name.casefold()
        if folded.startswith(":"):
            pseudo_headers[folded] = header.value
            continue
        if folded == "host":
            host_header = header.value
            continue
        if folded == "cookie":
            if not cookie_header_seen:
                # tls_client builds Cookie from its cookie jar, so keep it out
                # of headers while retaining its place in the wire ordering.
                header_order.append(_cookie_header_order_name(request))
                cookie_header_seen = True
            _read_cookie_header(header.value, cookie_values)
            continue
        if not name or folded in _REGENERATED_HEADERS:
            continue
        original_name = header_names.get(folded)
        if original_name is None:
            header_names[folded] = name
            request_headers[name] = header.value
            header_order.append(name)
        else:
            # tls_client accepts a mapping rather than repeated header pairs.
            request_headers[original_name] += ", " + header.value

    for cookie in request.cookies:
        if cookie.name:
            cookie_values[cookie.name] = cookie.value
    if cookie_values and not cookie_header_seen:
        # Some HARs provide parsed cookies without a raw Cookie header; their
        # relative position is unavailable, so mirror tls_client's append.
        header_order.append(_cookie_header_order_name(request))

    method = request.method or pseudo_headers.get(":method", "")
    if not method:
        raise ValueError(f"Request #{request.sequence} has no HTTP method.")

    url = _request_url(request, pseudo_headers, host_header)
    config: dict[str, Any] = {
        "sequence": request.sequence,
        "method": method,
        "url": url,
        "headers": request_headers,
        "header_order": header_order,
        "cookies": cookie_values,
        "force_http1": _force_http1(request),
    }

    mime_type = _request_mime_type(request, request_headers)
    if mime_type and "json" in mime_type.casefold():
        _add_json_body_or_raw_data(config, request.body)
    elif request.body is not None:
        config["data"] = request.body
        # HAR may record the post-data MIME type without a corresponding
        # Content-Type request header. Preserve it when available.
        if mime_type and not any(
            name.casefold() == "content-type" for name in request_headers
        ):
            content_type_name = "Content-Type"
            request_headers[content_type_name] = mime_type
            config["header_order"].append(content_type_name)

    return config


def _generate_single_request_python(
    request: HttpRequest,
    *,
    asynchronous: bool,
) -> str:
    config = _single_request_config(request)
    lines = [
        "# Generated by Reqvexa. Install the runtime with: pip install tls-client",
        "# Review captured credentials before sharing.",
    ]
    if asynchronous:
        lines.append("import asyncio")
    lines.extend((
        "import tls_client",
        "",
    ))

    if asynchronous:
        lines.extend((
            "async def run():",
            "    async with tls_client.AsyncSession() as session:",
        ))
        indent = "        "
        session_owner = "session.session"
    else:
        lines.extend((
            "session = tls_client.Session()",
            "",
        ))
        indent = ""
        session_owner = "session"

    lines.extend((
        f"{indent}url = {config['url']!r}",
        f"{indent}cookies = {config['cookies']!r}",
        f"{indent}headers = {config['headers']!r}",
        f"{indent}{session_owner}.header_order = list(headers.keys())",
        f"{indent}for header_name in tuple(headers):",
        f"{indent}    if header_name.casefold() in {{",
        f"{indent}        'cookie', 'content-length', 'host', 'transfer-encoding',",
        f"{indent}    }}:",
        f"{indent}        del headers[header_name]",
    ))

    body = request.body
    if body is not None:
        post_data: str | bytes
        try:
            post_data = body.decode("utf-8")
        except UnicodeDecodeError:
            post_data = body
        lines.append(f"{indent}post_data = {post_data!r}")
    lines.append(
        f"{indent}{session_owner}.force_http1 = {config['force_http1']!r}"
    )

    method = str(config["method"])
    method_name = method.casefold()
    arguments = ["url", "headers=headers", "cookies=cookies"]
    if body is not None:
        arguments.append("data=post_data")
    call_arguments = ", ".join(arguments)
    direct_methods = {"delete", "get", "head", "options", "patch", "post", "put"}
    if method_name in direct_methods:
        call = f"session.{method_name}({call_arguments})"
    else:
        call = (
            f"session.execute_request(method={method!r}, "
            f"url=url, headers=headers, cookies=cookies"
            f"{', data=post_data' if body is not None else ''})"
        )
    if asynchronous:
        call = "await " + call
    lines.append(f"{indent}response = {call}")

    if asynchronous:
        lines.extend((
            "        return response",
            "",
            "",
            'if __name__ == "__main__":',
            "    asyncio.run(run())",
        ))

    return "\n".join(lines) + "\n"


def _single_request_config(request: HttpRequest) -> dict[str, Any]:
    """Prepare raw single-request fields without the flow generator's cleanup."""
    pseudo_headers: dict[str, str] = {}
    headers: dict[str, str] = {}
    header_names: dict[str, str] = {}
    cookies: dict[str, str] = {}
    host_header = ""
    cookie_header_name = _cookie_header_order_name(request)

    for header in request.headers:
        name = header.name.strip()
        folded = name.casefold()
        if not name:
            continue
        if folded.startswith(":"):
            pseudo_headers[folded] = header.value
            continue
        if folded == "host":
            host_header = header.value
        if folded == "cookie":
            if cookie_header_name not in headers:
                headers[cookie_header_name] = header.value
            else:
                headers[cookie_header_name] += "; " + header.value
            _read_cookie_header(header.value, cookies)
            continue

        original_name = header_names.get(folded)
        if original_name is None:
            header_names[folded] = name
            headers[name] = header.value
        else:
            headers[original_name] += ", " + header.value

    for cookie in request.cookies:
        if cookie.name:
            cookies[cookie.name] = cookie.value
    if cookies and cookie_header_name not in headers:
        headers[cookie_header_name] = "; ".join(
            f"{name}={value}" for name, value in cookies.items()
        )

    method = request.method or pseudo_headers.get(":method", "")
    if not method:
        raise ValueError(f"Request #{request.sequence} has no HTTP method.")
    url = _request_url(request, pseudo_headers, host_header)
    mime_type = _request_mime_type(request, headers)
    if (
        request.body is not None
        and mime_type
        and not any(name.casefold() == "content-type" for name in headers)
    ):
        headers["Content-Type"] = mime_type

    return {
        "method": method,
        "url": url,
        "headers": headers,
        "cookies": cookies,
        "force_http1": _force_http1(request),
    }


def _dependency_bindings(
    requests: list[HttpRequest],
    configs: list[dict[str, Any]],
    analysis: Analysis,
) -> list[_DynamicBinding]:
    request_indexes = {request.id: index for index, request in enumerate(requests)}
    bindings: list[_DynamicBinding] = []
    binding_number = 0

    for consumer_index, request in enumerate(requests):
        for observation_id in analysis.request_observation_ids.get(request.id, ()):
            observation = analysis.observations_by_id.get(observation_id)
            if observation is None:
                continue
            version = analysis._version_for_observation(observation, request.sequence)
            if version is None:
                continue
            source = _dependency_source(
                analysis, observation, version, request, request_indexes,
            )
            if source is None:
                continue
            source_observation, producer_id = source
            is_request_cookie = observation.location.container in {
                "request.cookie",
                "request.cookies",
            }
            if (
                is_request_cookie
                and source_observation.location.container in {
                    "response.set_cookie",
                    "response.cookies",
                }
            ):
                if (
                    source_observation.raw_value == observation.raw_value
                    and _cookie_scope_matches(
                        source_observation, producer_id, request, analysis,
                    )
                ):
                    cookie_name = _cookie_name(observation)
                    if cookie_name:
                        # Let tls_client's cookie jar learn the response cookie
                        # and scope it to the issuing domain/path itself.
                        configs[consumer_index]["cookies"].pop(cookie_name, None)
                # A cookie outside its response scope cannot come from the
                # session jar, so retain the captured request cookie instead.
                continue

            marker = f"{_DYNAMIC_MARKER_PREFIX}{binding_number}__"
            bound, request_operations = _bind_request_observation(
                configs[consumer_index], request, observation, marker,
            )
            if not bound:
                continue
            binding_number += 1
            source_operations = _source_value_operations(
                source_observation.raw_value, observation.raw_value,
            )
            operations = (*source_operations, *request_operations)
            producer_index = request_indexes.get(producer_id)
            if (
                source_observation.location.container == "response.header"
                and producer_index is not None
            ):
                bindings.append(_DynamicBinding(
                    marker=marker,
                    producer_index=producer_index,
                    header_name=source_observation.location.path,
                    operations=operations,
                ))
                continue

            variable_name = f"manual_response_value_{binding_number}"
            source_label = source_observation.location.container.removeprefix("response.")
            source_path = re.sub(
                r"\s+", " ", source_observation.location.path or "$",
            ).replace("\0", "")
            if producer_index is None:
                note = (
                    f"TODO: Request #{analysis.capture.request(producer_id).sequence} "
                    "is not selected; provide this value manually or include its request."
                )
            else:
                note = (
                    f"TODO: Manually parse the required value from the {source_label} "
                    f"of request #{analysis.capture.request(producer_id).sequence} "
                    f"at {source_path}."
                )
            bindings.append(_DynamicBinding(
                marker=marker,
                producer_index=None,
                header_name=None,
                operations=operations,
                variable_name=variable_name,
                note=note,
            ))
    return bindings


def _dependency_source(
    analysis: Analysis,
    consumer_observation: ValueObservation,
    version: Any,
    consumer: HttpRequest,
    request_indexes: dict[str, int],
) -> tuple[ValueObservation, str] | None:
    candidates: list[tuple[int, int, int, str, ValueObservation]] = []
    for hypothesis in analysis.target_producers.get(version.version_id, ()):
        producer = hypothesis.producer
        if not producer.startswith("response_"):
            continue
        response_id = producer.removeprefix("response_")
        response_node = analysis.graph.nodes.get(response_id)
        if response_node is None:
            continue
        producer_id = str(response_node.payload.get("request_id", ""))
        producer_index = request_indexes.get(producer_id)
        if producer_index is None:
            continue
        producer_request = analysis.capture.request(producer_id)
        if producer_request.sequence >= consumer.sequence:
            continue
        for source in analysis.observations:
            if (
                source.response_id != response_id
                or not _observations_match(source, consumer_observation)
            ):
                continue
            source_priority = {
                "response.set_cookie": 0,
                "response.cookies": 0,
                "response.header": 1,
            }.get(source.location.container, 2)
            candidates.append((
                producer_request.sequence,
                -source_priority,
                -producer_index,
                source.observation_id,
                source,
            ))
    if not candidates:
        return None
    *_, source = max(candidates, key=lambda item: item[:-1])
    if source.request_id is None:
        return None
    return source, source.request_id


def _observations_match(
    source: ValueObservation,
    consumer: ValueObservation,
) -> bool:
    if source.normalized_value == consumer.normalized_value:
        return True
    source_value = source.normalized_value
    consumer_value = consumer.normalized_value
    if _strip_bearer(source_value) == _strip_bearer(consumer_value):
        return True
    if unquote(source_value) == unquote(consumer_value):
        return True
    return (
        _decode_base64(source_value) == consumer_value
        or _decode_base64(consumer_value) == source_value
    )


def _decode_base64(value: str) -> str | None:
    try:
        decoded = base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))
        return decoded.decode("utf-8")
    except (ValueError, UnicodeDecodeError):
        return None


def _strip_bearer(value: str) -> str:
    parts = value.split(None, 1)
    return parts[1] if parts and parts[0].casefold() == "bearer" and len(parts) == 2 else value


def _cookie_name(observation: ValueObservation) -> str | None:
    hint = next(
        (item for item in observation.semantic_hints if item.startswith("cookie.")),
        "",
    )
    if hint:
        return hint.removeprefix("cookie.")
    path = observation.location.path or ""
    return path.split("@", 1)[0] or None


def _cookie_scope_matches(
    observation: ValueObservation,
    producer_id: str,
    consumer: HttpRequest,
    analysis: Analysis,
) -> bool:
    path = observation.location.path or ""
    _, _, scope = path.partition("@")
    domain, cookie_path, secure, host_only, *_ = (scope.split("|") + [""] * 5)[:5]
    producer = analysis.capture.request(producer_id)
    producer_url = urlsplit(producer.url)
    consumer_url = urlsplit(consumer.url)
    producer_host = (producer_url.hostname or "").casefold()
    consumer_host = (consumer_url.hostname or "").casefold()
    cookie_domain = domain.lstrip(".").casefold()
    if not producer_host or not consumer_host:
        return False
    if cookie_domain:
        if consumer_host != cookie_domain and not consumer_host.endswith(
            f".{cookie_domain}"
        ):
            return False
    elif consumer_host != producer_host:
        return False
    if host_only.casefold() == "true" and consumer_host != producer_host:
        return False
    if secure.casefold() == "true" and consumer_url.scheme.casefold() != "https":
        return False
    required_path = cookie_path or "/"
    consumer_path = consumer_url.path or "/"
    if not consumer_path.startswith(required_path):
        return False
    if (
        len(consumer_path) > len(required_path)
        and not required_path.endswith("/")
        and consumer_path[len(required_path)] != "/"
    ):
        return False
    return True


def _source_value_operations(source: str, target: str) -> tuple[str, ...]:
    candidates: tuple[tuple[str, ...], ...] = (
        (),
        ("strip_whitespace",),
        ("url_decode",),
        ("url_encode",),
        ("base64_decode",),
        ("base64_urlsafe_decode",),
        ("base64_encode",),
        ("base64_urlsafe_encode",),
        ("base64_encode_unpadded",),
        ("base64_urlsafe_encode_unpadded",),
        ("bearer_strip",),
        ("bearer_add",),
        ("strip_whitespace", "url_decode"),
        ("url_decode", "strip_whitespace"),
        ("url_decode", "url_decode"),
        ("strip_whitespace", "url_decode", "url_decode"),
        ("url_decode", "base64_decode"),
        ("url_decode", "base64_urlsafe_decode"),
        ("base64_decode", "url_decode"),
        ("base64_urlsafe_decode", "url_decode"),
        ("strip_whitespace", "base64_decode"),
        ("strip_whitespace", "base64_urlsafe_decode"),
    )
    for operations in candidates:
        try:
            if _apply_transform_static(source, operations) == target:
                return operations
        except (ValueError, UnicodeDecodeError):
            continue
    return ()


def _apply_transform_static(value: str, operations: tuple[str, ...]) -> str:
    for operation in operations:
        if operation == "strip_whitespace":
            value = " ".join(value.strip().split())
        elif operation == "url_decode":
            value = unquote(value)
        elif operation == "url_encode":
            value = quote(value, safe="")
        elif operation in {"base64_decode", "base64_urlsafe_decode"}:
            value = base64.urlsafe_b64decode(
                value + "=" * (-len(value) % 4),
            ).decode("utf-8")
        elif operation in {
            "base64_encode",
            "base64_urlsafe_encode",
            "base64_encode_unpadded",
            "base64_urlsafe_encode_unpadded",
        }:
            encoded = base64.urlsafe_b64encode(value.encode("utf-8")).decode("ascii")
            if operation.startswith("base64_encode") and not operation.startswith(
                "base64_urlsafe"
            ):
                encoded = base64.b64encode(value.encode("utf-8")).decode("ascii")
            if operation.endswith("_unpadded"):
                encoded = encoded.rstrip("=")
            value = encoded
        elif operation == "bearer_strip":
            value = _strip_bearer(value)
        elif operation == "bearer_add":
            value = f"Bearer {value}"
        elif operation.startswith("query_quote_safe="):
            value = quote(value, safe=operation.partition("=")[2])
        elif operation.startswith("query_quote_plus_safe="):
            value = quote_plus(value, safe=operation.partition("=")[2])
        elif operation.startswith("form_quote_safe="):
            value = quote_plus(value, safe=operation.partition("=")[2])
        elif operation == "query_quote":
            value = quote(value, safe="")
        elif operation in {"query_quote_plus", "form_quote"}:
            value = quote_plus(value, safe="")
    return value


def _bind_request_observation(
    config: dict[str, Any],
    request: HttpRequest,
    observation: ValueObservation,
    marker: str,
) -> tuple[bool, tuple[str, ...]]:
    container = observation.location.container
    path = observation.location.path or ""
    original = observation.raw_value

    if container == "request.header":
        for name, value in tuple(config["headers"].items()):
            if name.casefold() == path.casefold() and original in value:
                config["headers"][name] = value.replace(original, marker)
                return True, ()
        return False, ()

    if container == "request.query":
        config["url"], operations, replaced = _replace_url_query(
            config["url"], path, original, marker,
        )
        return replaced, operations

    if container == "request.body":
        if "json" in config:
            replaced = _replace_json_path(
                config["json"], path, original, marker,
            )
            return replaced, ()
        body = config.get("data")
        if isinstance(body, bytes):
            mime_type = _request_mime_type(request, config["headers"]) or ""
            if "form-urlencoded" in mime_type.casefold():
                config["data"], operations, replaced = _replace_form_body(
                    body, path, original, marker,
                )
                return replaced, operations
            original_bytes = original.encode("utf-8")
            if original_bytes in body:
                config["data"] = body.replace(original_bytes, marker.encode("ascii"))
                return True, ()
        return False, ()

    if container in {"request.cookie", "request.cookies"}:
        cookie_name = _cookie_name(observation)
        if cookie_name and cookie_name in config["cookies"]:
            config["cookies"][cookie_name] = marker
            return True, ()
    return False, ()


def _replace_url_query(
    url: str,
    key: str,
    original: str,
    marker: str,
) -> tuple[str, tuple[str, ...], bool]:
    parts = urlsplit(url)
    query_parts: list[str] = []
    replaced = False
    use_plus = False
    encoding_raw_value = ""
    for part in parts.query.split("&"):
        raw_key, separator, raw_value = part.partition("=")
        if (
            unquote_plus(raw_key) == key
            and unquote_plus(raw_value) == original
        ):
            if not replaced:
                encoding_raw_value = raw_value
            use_plus = use_plus or "+" in raw_value
            raw_value = marker
            replaced = True
        query_parts.append(f"{raw_key}{separator}{raw_value}")
    operations = (_query_encoding_operation(
        encoding_raw_value, use_plus=use_plus,
    ),)
    return (
        urlunsplit((parts.scheme, parts.netloc, parts.path, "&".join(query_parts), parts.fragment)),
        operations,
        replaced,
    )


def _replace_form_body(
    body: bytes,
    key: str,
    original: str,
    marker: str,
) -> tuple[bytes, tuple[str, ...], bool]:
    try:
        text = body.decode("utf-8")
    except UnicodeDecodeError:
        return body, (), False
    parts: list[str] = []
    replaced = False
    encoding_raw_value = ""
    for part in text.split("&"):
        raw_key, separator, raw_value = part.partition("=")
        if unquote_plus(raw_key) == key and unquote_plus(raw_value) == original:
            if not replaced:
                encoding_raw_value = raw_value
            raw_value = marker
            replaced = True
        parts.append(f"{raw_key}{separator}{raw_value}")
    return (
        "&".join(parts).encode("utf-8"),
        (_query_encoding_operation(encoding_raw_value, use_plus=True, form=True),),
        replaced,
    )


def _query_encoding_operation(
    original_raw_value: str,
    *,
    use_plus: bool = False,
    form: bool = False,
) -> str:
    reserved = set(":/?#[]@!$&'()*+,;=")
    # Preserve reserved characters only when this capture sent them literally.
    # A literal '+' in a query/form value represents a space, so keep it
    # percent-encoded when it is actual data rather than a space separator.
    safe = "".join(
        character for character in dict.fromkeys(original_raw_value)
        if character in reserved and character not in {"&", "+"}
    )
    if form:
        return f"form_quote_safe={safe}"
    if use_plus:
        return f"query_quote_plus_safe={safe}"
    return f"query_quote_safe={safe}"


def _replace_json_path(
    value: Any,
    path: str,
    original: str,
    marker: str,
) -> bool:
    if path == "$":
        return False
    segments: list[str | int] = []
    for key, index in re.findall(r"\.([^.[\]]+)|\[(\d+)\]", path.removeprefix("$")):
        segments.append(int(index) if index else key)
    if not segments:
        return False
    current = value
    for segment in segments[:-1]:
        try:
            current = current[segment]
        except (IndexError, KeyError, TypeError):
            return False
    last = segments[-1]
    try:
        found = current[last]
        if str(found) != original:
            return False
        current[last] = marker
    except (IndexError, KeyError, TypeError):
        return False
    return True


def _render_manual_bindings(bindings: list[_DynamicBinding]) -> str:
    if not bindings:
        return "MANUAL_BINDINGS = {}\n\n"
    lines: list[str] = []
    values: list[str] = []
    for binding in bindings:
        assert binding.variable_name is not None
        lines.extend((
            f"# {binding.note}",
            f'{binding.variable_name} = "REPLACE_ME"',
        ))
        values.append(
            f"    {binding.marker!r}: "
            f"({binding.variable_name!r}, {binding.operations!r}),"
        )
    return "\n".join(lines) + "\nMANUAL_BINDINGS = {\n" + "\n".join(values) + "\n}\n\n"


def _render_header_bindings(bindings: list[_DynamicBinding]) -> str:
    grouped: dict[int, list[tuple[str, str, tuple[str, ...]]]] = {}
    for binding in bindings:
        assert binding.producer_index is not None
        assert binding.header_name is not None
        grouped.setdefault(binding.producer_index, []).append((
            binding.marker,
            binding.header_name,
            binding.operations,
        ))
    return pformat(grouped, width=88, sort_dicts=False)


