def _request_url(
    request: HttpRequest,
    pseudo_headers: dict[str, str],
    host_header: str,
) -> str:
    url = request.url
    parts = urlsplit(url)
    if parts.scheme and parts.netloc:
        return url

    authority = (
        pseudo_headers.get(":authority")
        or host_header
        or parts.netloc
    )
    scheme = pseudo_headers.get(":scheme") or parts.scheme or "https"
    path = pseudo_headers.get(":path") or parts.path or "/"
    if parts.query and "?" not in path:
        path = f"{path}?{parts.query}"
    if not authority:
        raise ValueError(
            f"Request #{request.sequence} has no absolute URL or :authority header."
        )
    return urlunsplit((scheme, authority, path.split("?", 1)[0],
                       path.split("?", 1)[1] if "?" in path else "", ""))


def _read_cookie_header(value: str, cookies: dict[str, str]) -> None:
    for item in value.split(";"):
        name, separator, cookie_value = item.strip().partition("=")
        if separator and name:
            cookies[name] = cookie_value.strip()


def _request_mime_type(
    request: HttpRequest,
    headers: dict[str, str],
) -> str | None:
    header_mime = next(
        (value for name, value in headers.items()
         if name.casefold() == "content-type"),
        None,
    )
    if header_mime:
        return header_mime.split(";", 1)[0].strip()
    post_data = request.raw.get("postData")
    if isinstance(post_data, dict):
        mime = post_data.get("mimeType")
        if mime:
            return str(mime).split(";", 1)[0].strip()
    return None


def _add_json_body_or_raw_data(
    config: dict[str, Any],
    body: bytes | None,
) -> None:
    if body is None:
        return
    try:
        decoded = json.loads(body.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError):
        config["data"] = body
        return
    # tls_client serializes dicts/lists passed via json=. Other JSON scalars
    # are kept as bytes to avoid changing their exact request body.
    if isinstance(decoded, (dict, list)):
        config["json"] = decoded
    else:
        config["data"] = body


def _force_http1(request: HttpRequest) -> bool:
    version = str(request.raw.get("httpVersion", "")).upper()
    return version.startswith("HTTP/1.")


def _cookie_header_order_name(request: HttpRequest) -> str:
    version = str(request.raw.get("httpVersion", "")).upper()
    has_pseudo_headers = any(
        header.name.strip().startswith(":") for header in request.headers
    )
    if (
        version.startswith(("HTTP/2", "HTTP/3", "H2", "H3"))
        or has_pseudo_headers
    ):
        return "cookie"
    return "Cookie"


