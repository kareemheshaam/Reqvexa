def _resolve(value, dynamic_values):
    if isinstance(value, str):
        for marker, replacement in dynamic_values.items():
            value = value.replace(marker, replacement)
        return value
    if isinstance(value, bytes):
        for marker, replacement in dynamic_values.items():
            value = value.replace(marker.encode("ascii"), replacement.encode("utf-8"))
        return value
    if isinstance(value, dict):
        return {key: _resolve(item, dynamic_values) for key, item in value.items()}
    if isinstance(value, list):
        return [_resolve(item, dynamic_values) for item in value]
    return value


def _response_header(response, name):
    value = response.headers.get(name)
    if value is None:
        raise RuntimeError(f"Required response header {name!r} was not returned.")
    if isinstance(value, (list, tuple)):
        if not value:
            raise RuntimeError(f"Required response header {name!r} was empty.")
        value = value[-1]
    return str(value)


def _request_kwargs(request, dynamic_values):
    headers = _resolve(request["headers"], dynamic_values)
    cookies = _resolve(request["cookies"], dynamic_values)
    if cookies:
        headers["Cookie"] = "; ".join(
            f"{name}={value}" for name, value in cookies.items()
        )
    request_kwargs = {
        "headers": headers,
        "header_order": request["header_order"],
        "allow_redirects": False,
    }
    if "json" in request:
        request_kwargs["json"] = _resolve(request["json"], dynamic_values)
    elif "data" in request:
        request_kwargs["data"] = _resolve(request["data"], dynamic_values)
    return request_kwargs


